def t(VariableName, Inputs=None, Lang='FA'):
    """Format a registered translation without executing Python code."""
    template = globals().get(f'{VariableName}_{Lang}')
    if not isinstance(template, str):
        raise KeyError(f'Unknown text template: {VariableName}_{Lang}')
    return template.format(*(Inputs if Inputs is not None else []))
